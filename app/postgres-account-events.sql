DO $$
BEGIN
    IF to_regclass('geo_cities') IS NOT NULL THEN
        UPDATE users u
        SET profile_location = jsonb_build_object(
                'country', country.name, 'code', u.country_code,
                'city', city.name, 'region', city.region),
            location_country = u.country_code,
            location_city = city.name
        FROM geo_countries country
        LEFT JOIN geo_cities city ON city.country = country.code
        WHERE u.country_code = country.code AND city.id = u.city_id
          AND u.profile_location IS NULL;

        UPDATE users u
        SET profile_location = jsonb_build_object('country', country.name, 'code', country.code),
            location_country = country.code
        FROM geo_countries country
        WHERE u.country_code = country.code AND u.profile_location IS NULL;
    END IF;
END $$;
