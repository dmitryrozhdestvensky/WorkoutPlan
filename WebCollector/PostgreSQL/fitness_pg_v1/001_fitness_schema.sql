BEGIN;
CREATE SCHEMA IF NOT EXISTS fitness;

CREATE TABLE IF NOT EXISTS fitness.sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    base_url text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fitness.import_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint REFERENCES fitness.sources(id),
    input_path text,
    input_sha256 text,
    status text NOT NULL DEFAULT 'started' CHECK (status IN ('started','completed','failed')),
    rows_read integer NOT NULL DEFAULT 0,
    rows_inserted integer NOT NULL DEFAULT 0,
    rows_updated integer NOT NULL DEFAULT 0,
    rows_skipped integer NOT NULL DEFAULT 0,
    notes text,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz
);

CREATE TABLE IF NOT EXISTS fitness.source_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES fitness.sources(id),
    profile_url text,
    source_profile_id text,
    raw_name text,
    normalized_name text,
    city text,
    clubs text,
    specialty text,
    biography text,
    raw_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    collected_at timestamptz,
    imported_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz,
    import_run_id bigint REFERENCES fitness.import_runs(id),
    CHECK (profile_url IS NOT NULL OR source_profile_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fitness_source_url
  ON fitness.source_profiles(source_id, profile_url) WHERE profile_url IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_fitness_source_profile_id
  ON fitness.source_profiles(source_id, source_profile_id) WHERE source_profile_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_fitness_source_profile_name ON fitness.source_profiles(normalized_name);
CREATE INDEX IF NOT EXISTS ix_fitness_source_profile_raw_data ON fitness.source_profiles USING gin(raw_data);

CREATE TABLE IF NOT EXISTS fitness.profile_socials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_profile_id bigint NOT NULL REFERENCES fitness.source_profiles(id) ON DELETE CASCADE,
    platform text NOT NULL,
    account_url text NOT NULL,
    account_external_id text,
    verification_status text NOT NULL DEFAULT 'unverified'
       CHECK (verification_status IN ('unverified','verified','rejected')),
    evidence text,
    collected_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(source_profile_id, platform, account_url)
);

CREATE TABLE IF NOT EXISTS fitness.name_normalizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_profile_id bigint NOT NULL REFERENCES fitness.source_profiles(id) ON DELETE CASCADE,
    provider text NOT NULL,
    input_name text NOT NULL,
    result jsonb NOT NULL DEFAULT '{}'::jsonb,
    quality_code integer,
    checked_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(source_profile_id, provider, input_name)
);

CREATE TABLE IF NOT EXISTS fitness.trainers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text,
    normalized_name text,
    city text,
    bio text,
    review_status text NOT NULL DEFAULT 'provisional'
       CHECK (review_status IN ('provisional','reviewed','verified')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fitness.trainer_profile_links (
    trainer_id bigint NOT NULL REFERENCES fitness.trainers(id) ON DELETE CASCADE,
    source_profile_id bigint NOT NULL UNIQUE REFERENCES fitness.source_profiles(id) ON DELETE CASCADE,
    link_method text NOT NULL DEFAULT 'manual',
    reviewed_at timestamptz,
    evidence text,
    PRIMARY KEY(trainer_id, source_profile_id)
);

CREATE TABLE IF NOT EXISTS fitness.trainer_user_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id bigint NOT NULL REFERENCES fitness.trainers(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES public.users(id),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','verified','rejected')),
    evidence text,
    created_at timestamptz NOT NULL DEFAULT now(),
    verified_at timestamptz,
    UNIQUE(trainer_id, user_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fitness_verified_user
  ON fitness.trainer_user_links(user_id) WHERE status = 'verified';

CREATE TABLE IF NOT EXISTS fitness.merge_candidates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    left_profile_id bigint NOT NULL REFERENCES fitness.source_profiles(id) ON DELETE CASCADE,
    right_profile_id bigint NOT NULL REFERENCES fitness.source_profiles(id) ON DELETE CASCADE,
    score numeric(5,4),
    evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'pending'
       CHECK (status IN ('pending','confirmed','rejected')),
    reviewed_at timestamptz,
    CHECK (left_profile_id < right_profile_id),
    UNIQUE(left_profile_id, right_profile_id)
);

COMMIT;
