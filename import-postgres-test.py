"""Import a read-only SQLite snapshot into an empty local PostgreSQL test database."""
import os
import argparse
import sqlite3
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TABLES = (
    'users', 'exercises', 'workouts', 'results', 'tag_groups', 'tags',
    'account_count_tracking', 'account_count_events',
    'social_accounts_provider', 'social_accounts',
)
IDENTITY_TABLES = {
    'users', 'exercises', 'workouts', 'tag_groups', 'tags',
    'social_accounts_provider', 'social_accounts',
}


def literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, int):
        return str(value)
    return "'" + value.replace("'", "''") + "'"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--database', choices=('workoutplan_test', 'workoutplan'), default='workoutplan_test')
    parser.add_argument('--source', type=Path, default=ROOT / 'data' / 'app.sqlite3')
    options = parser.parse_args()
    target = options.database
    source = options.source.resolve()
    statements = ['BEGIN;', "SET LOCAL TIME ZONE 'UTC';", 'SET LOCAL standard_conforming_strings = on;']
    counts = {}
    with sqlite3.connect(source.as_uri() + '?mode=ro', uri=True) as db:
        db.execute('BEGIN')
        for table in TABLES:
            schema = db.execute('SELECT sql FROM sqlite_master WHERE name=?', (table,)).fetchone()[0]
            if table in IDENTITY_TABLES:
                schema = schema.replace('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 1)
            for column in ('registered_at', 'started_at', 'occurred_at', 'updated'):
                schema = schema.replace(f'{column} TEXT', f'{column} TIMESTAMPTZ')
            statements.append(schema + ';')
            rows = db.execute(f'SELECT * FROM {table}').fetchall()
            counts[table] = len(rows)
            for row in rows:
                statements.append(f"INSERT INTO {table} VALUES ({', '.join(map(literal, row))});")
            if table in IDENTITY_TABLES:
                statements.append(
                    f"SELECT setval(pg_get_serial_sequence('{table}','id'), "
                    f"COALESCE(MAX(id),1), MAX(id) IS NOT NULL) FROM {table};"
                )
            statements.append(
                f"DO $$ BEGIN IF (SELECT count(*) FROM {table}) <> {len(rows)} "
                f"THEN RAISE EXCEPTION 'Row count mismatch: {table}'; END IF; END $$;"
            )
    statements.append('COMMIT;')
    password = (ROOT / 'data' / 'postgres-test-password.txt').read_text(encoding='ascii').strip()
    executable = Path('W:/data/postgres17/pgsql/bin/psql.exe')
    result = subprocess.run(
        [str(executable), '-X', '-w', '-h', '127.0.0.1', '-p', '15432',
         '-U', 'workoutplan_test', '-d', target, '-v', 'ON_ERROR_STOP=1', '-q'],
        input='\n'.join(statements).encode('utf-8'),
        env={**os.environ, 'PGPASSWORD': password, 'PGCLIENTENCODING': 'UTF8'},
        capture_output=True,
    )
    if result.returncode:
        # SQL error details may contain imported account data.
        raise SystemExit('Import failed and was rolled back. Check that the test database is reachable and empty.')
    for table, count in counts.items():
        print(f'{table}: {count}')


if __name__ == '__main__':
    main()
